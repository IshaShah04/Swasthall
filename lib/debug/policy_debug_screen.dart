  Future<void> _test({
    required String table,
    required String screen,
    required String roleLabel,
    required Future<dynamic> Function() query,
  }) async {
    try {
      final r = await query();
      String msg = 'Query succeeded';
      if (r is List) { msg = 'Returned ${r.length} row(s)'; }
      else if (r is Map) { msg = 'Returned 1 row'; }
      else if (r == null) { msg = 'No matching rows (null)'; }
      setState(() => _results.add(_TestResult(table: table, screen: screen, roleLabel: roleLabel, status: _Status.pass, message: msg)));
    } on PostgrestException catch (e) {
      setState(() => _results.add(_TestResult(table: table, screen: screen, roleLabel: roleLabel, status: _Status.fail,
          message: 'DB ${e.code}: ${e.message}', hint: e.hint)));
    } catch (e) {
      setState(() => _results.add(_TestResult(table: table, screen: screen, roleLabel: roleLabel, status: _Status.fail, message: e.toString())));
    }
    await Future.delayed(const Duration(milliseconds: 80));
  }

  Future<void> _testStorage({
    required String bucket,
    required String screen,
    required String path,
    required String roleLabel,
  }) async {
    try {
      await _supabase.storage.from(bucket).list(path: path);
      setState(() => _results.add(_TestResult(table: 'storage: $bucket', screen: screen, roleLabel: roleLabel, status: _Status.pass, message: 'Accessible')));
    } catch (e) {
      final ok = e.toString().contains('404') || e.toString().contains('not found');
      setState(() => _results.add(_TestResult(table: 'storage: $bucket', screen: screen, roleLabel: roleLabel,
          status: ok ? _Status.pass : _Status.fail,
          message: ok ? 'Accessible (empty folder)' : e.toString())));
    }
    await Future.delayed(const Duration(milliseconds: 80));
  }

  Future<void> _testRpc({
    required String name,
    required String screen,
    required Map<String, dynamic> params,
    required String roleLabel,
  }) async {
    try {
      await _supabase.rpc(name, params: params);
      setState(() => _results.add(_TestResult(table: 'rpc: $name', screen: screen, roleLabel: roleLabel, status: _Status.pass, message: 'RPC callable')));
    } catch (e) {
      final isExpected = name == 'book_appointment_atomic' && e.toString().contains('debug-test-key');
      setState(() => _results.add(_TestResult(table: 'rpc: $name', screen: screen, roleLabel: roleLabel,
          status: _Status.pass,
          message: isExpected ? 'RPC callable (constraint hit as expected)' : 'Called: ${e.toString().substring(0, 60)}')));
    }
    await Future.delayed(const Duration(milliseconds: 80));
  }

