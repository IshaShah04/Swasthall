  Future<void> _runSchemaAudit() async {
    setState(() { _auditRunning = true; _auditResults = []; _sqlScript = ''; });

    final List<_TableAudit> audits = [];
    final StringBuffer sql = StringBuffer();
    sql.writeln('-- ═══════════════════════════════════════════════════');
    sql.writeln('-- Swasthall Schema Cleanup SQL');
    sql.writeln('-- Generated: ${DateTime.now().toIso8601String().substring(0,19)}');
    sql.writeln('-- REVIEW CAREFULLY before running in production!');
    sql.writeln('-- Uncomment a line only when you are 100% sure.');
    sql.writeln('-- ═══════════════════════════════════════════════════\n');

    for (final entry in _usedSchema.entries) {
      final tableName = entry.key;
      final usedCols = entry.value.toSet();
      final isView = _views.contains(tableName);

      try {
        final probe = await _supabase.from(tableName).select().limit(1);
        List<String> dbCols = [];
        if (probe.isNotEmpty) {
          dbCols = probe.first.keys.toList();
        }

        final unusedCols = dbCols
            .where((c) => !usedCols.contains(c))
            .where((c) => !_isSafeSystemCol(c))
            .toList();

        audits.add(_TableAudit(
          tableName: tableName,
          isView: isView,
          usedColumns: usedCols.where((c) => dbCols.contains(c)).toList(),
          allDbColumns: dbCols,
          unusedColumns: unusedCols,
          accessible: true,
        ));

        if (unusedCols.isNotEmpty && !isView) {
          sql.writeln('-- ── $tableName: ${unusedCols.length} possibly unused column(s)');
          for (final col in unusedCols) {
            sql.writeln('-- ALTER TABLE $tableName DROP COLUMN IF EXISTS "$col";');
          }
          sql.writeln();
        }
      } catch (e) {
        audits.add(_TableAudit(
          tableName: tableName, isView: isView,
          usedColumns: usedCols.toList(), allDbColumns: [],
          unusedColumns: [], accessible: false, error: e.toString(),
        ));
      }
      await Future.delayed(const Duration(milliseconds: 60));
    }

    // Low-usage tables section
    sql.writeln('\n-- ═══════════════════════════════════════════════════');
    sql.writeln('-- LOW-USAGE TABLES — Review before dropping');
    sql.writeln('-- Check FK constraints with:');
    sql.writeln('-- SELECT * FROM information_schema.referential_constraints WHERE unique_constraint_schema=\'public\';');
    sql.writeln('-- ═══════════════════════════════════════════════════\n');
    for (final t in _lowUsageTables) {
      sql.writeln('-- ${t.table}: ${t.reason}');
      sql.writeln('-- DROP TABLE IF EXISTS ${t.table} CASCADE;');
      sql.writeln();
    }

    audits.sort((a, b) {
      if (!a.accessible && b.accessible) return -1;
      if (a.accessible && !b.accessible) return 1;
      return b.unusedColumns.length.compareTo(a.unusedColumns.length);
    });

    setState(() {
      _auditResults = audits;
      _sqlScript = sql.toString();
      _auditRunning = false;
    });
  }

  bool _isSafeSystemCol(String col) =>
      {'id','created_at','updated_at','deleted_at','uuid'}.contains(col);

