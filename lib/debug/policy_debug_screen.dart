class _AuditTile extends StatelessWidget {
  final _TableAudit audit;
  const _AuditTile({required this.audit});

  @override
  Widget build(BuildContext context) {
    final hasIssues = audit.unusedColumns.isNotEmpty;
    final color = !audit.accessible ? Colors.red : hasIssues ? Colors.orange : Colors.green;

    return Container(
      margin: const EdgeInsets.only(bottom: 8),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.05),
        border: Border.all(color: color.withValues(alpha: 0.3), width: 0.5),
        borderRadius: BorderRadius.circular(8),
      ),
      child: Theme(
        data: Theme.of(context).copyWith(dividerColor: Colors.transparent),
        child: ExpansionTile(
          tilePadding: const EdgeInsets.symmetric(horizontal: 10, vertical: 2),
          leading: Icon(!audit.accessible ? Icons.error_outline :
            hasIssues ? Icons.warning_amber_outlined : Icons.check_circle_outline,
            size: 18, color: color),
          title: Row(children: [
            Expanded(child: Text(
              '${audit.tableName}${audit.isView ? ' (view)' : ''}',
              style: TextStyle(fontSize: 13, fontWeight: FontWeight.w600, color: color),
            )),
            if (hasIssues)
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(color: Colors.orange.withValues(alpha: 0.15), borderRadius: BorderRadius.circular(10)),
                child: Text('${audit.unusedColumns.length} unused',
                  style: const TextStyle(fontSize: 10, color: Colors.orange, fontWeight: FontWeight.bold)),
              ),
          ]),
          subtitle: audit.accessible
            ? Text('${audit.allDbColumns.length} DB cols · ${audit.usedColumns.length} used in app',
                style: const TextStyle(fontSize: 10, color: Colors.grey))
            : Text(audit.error ?? 'Not accessible',
                style: const TextStyle(fontSize: 10, color: Colors.red)),
          children: [
            Padding(
              padding: const EdgeInsets.fromLTRB(16, 0, 16, 12),
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                if (audit.unusedColumns.isNotEmpty) ...[
                  const Text('Possibly unused:', style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold, color: Colors.orange)),
                  const SizedBox(height: 4),
                  Wrap(spacing: 6, runSpacing: 4,
                    children: audit.unusedColumns.map((col) => Container(
                      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                      decoration: BoxDecoration(
                        color: Colors.orange.withValues(alpha: 0.1),
                        borderRadius: BorderRadius.circular(4),
                        border: Border.all(color: Colors.orange.withValues(alpha: 0.3)),
                      ),
                      child: Text(col, style: const TextStyle(fontSize: 11, fontFamily: 'monospace')),
                    )).toList(),
                  ),
                  const SizedBox(height: 10),
                ],
                if (audit.usedColumns.isNotEmpty) ...[
                  const Text('Used in app:', style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold, color: Colors.green)),
                  const SizedBox(height: 4),
                  Wrap(spacing: 6, runSpacing: 4,
                    children: audit.usedColumns.map((col) => Container(
                      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                      decoration: BoxDecoration(color: Colors.green.withValues(alpha: 0.08), borderRadius: BorderRadius.circular(4)),
                      child: Text(col, style: const TextStyle(fontSize: 11, fontFamily: 'monospace', color: Colors.green)),
                    )).toList(),
                  ),
                ],
              ]),
            ),
          ],
        ),
      ),
    );
  }
}

class _ResultTile extends StatelessWidget {
  final _TestResult result;
  const _ResultTile({required this.result});
  @override
  Widget build(BuildContext context) {
    final isPass = result.status == _Status.pass;
    final color = isPass ? Colors.green : Colors.red;

    Color roleBadgeColor = Colors.blueGrey;
    if (result.roleLabel == 'patient') {
      roleBadgeColor = const Color(0xFF6366F1);
    } else if (result.roleLabel == 'doctor') {
      roleBadgeColor = const Color(0xFF0EA5E9);
    } else if (result.roleLabel == 'hospital/clinic') {
      roleBadgeColor = const Color(0xFFEC4899);
    } else if (result.roleLabel == 'ALL') {
      roleBadgeColor = Colors.grey;
    }

    return Container(
      margin: const EdgeInsets.only(bottom: 8),
      padding: const EdgeInsets.all(10),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.06),
        border: Border.all(color: color.withValues(alpha: 0.3), width: 0.5),
        borderRadius: BorderRadius.circular(8),
      ),
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Row(children: [
          Icon(isPass ? Icons.check_circle_outline : Icons.error_outline, size: 14, color: color),
          const SizedBox(width: 6),
          Expanded(child: Text(result.table, style: TextStyle(fontSize: 13, fontWeight: FontWeight.w600, color: color))),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 7, vertical: 2),
            decoration: BoxDecoration(
              color: roleBadgeColor.withValues(alpha: 0.12),
              borderRadius: BorderRadius.circular(8),
              border: Border.all(color: roleBadgeColor.withValues(alpha: 0.3)),
            ),
            child: Text(result.roleLabel,
              style: TextStyle(fontSize: 10, color: roleBadgeColor, fontWeight: FontWeight.w600)),
          ),
        ]),
        const SizedBox(height: 3),
        Text('Screen: ${result.screen}', style: TextStyle(fontSize: 11, color: Theme.of(context).colorScheme.onSurface.withValues(alpha: 0.5))),
        const SizedBox(height: 3),
        Text(result.message, style: TextStyle(fontSize: 12, color: isPass ? Colors.green[800] : Colors.red[800])),
        if (result.hint != null)
          Padding(padding: const EdgeInsets.only(top: 2),
            child: Text('Hint: ${result.hint}', style: TextStyle(fontSize: 11, color: Colors.orange[800]))),
      ]),
    );
  }
}

